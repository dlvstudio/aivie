"""Gom ~1 tỷ token CODE chất-lượng cho expert lập-trình của 1.3B (công-thức kiểu Phi-1: code "giống giáo-trình" +
bài tập có lời-giải) — mã-hoá bằng bộ tách-từ của 1.3B (checkpoints/bpe_v1.json, ~2,33 ký-tự/token với code).

  py    codeparrot/codeparrot-clean (Python GitHub, đã lọc trùng) → LỌC: không tự-sinh · 300–30.000 ký-tự ·
        dòng dài ≤150, TB ≤60 (bỏ file nén/dữ-liệu) · tỉ-lệ chữ ≥0,35 · CÓ HÀM (def) · CÓ GIẢI-THÍCH
        (docstring hoặc ≥5% dòng là chú-thích) → data/code_pt/py_XXX.npy (100M token/mảnh)
  inst  Magicoder-OSS-Instruct-75K + CodeFeedback-Filtered (157K) + Evol-Instruct-Code-80k → khuôn "Hỏi:/Đáp:"
        → data/code_pt/inst_000.npy

    PYTHONPATH=src python scripts/build_code_corpus.py --target 900000000
"""
from __future__ import annotations
import argparse, json, os, sys, time
from multiprocessing import Pool
import numpy as np

sys.path.insert(0, "src")
OUT = "data/code_pt"
TOK = None


def _init():
    global TOK
    from nn_aivie.core.tokenizer import BPETokenizer
    TOK = BPETokenizer.load("checkpoints/bpe_v1.json")


def _enc(texts):
    eos = TOK.token_to_id["<EOS>"]
    out = []
    for t in texts:
        out.extend(TOK.encode(t)); out.append(eos)
    return np.asarray(out, dtype=np.uint16)


def keep(r):
    c = r["content"]
    if r.get("autogenerated") in (True, "True") or not (300 <= len(c) <= 30000):
        return False
    if float(r["line_max"]) > 150 or float(r["line_mean"]) > 60 or float(r["alpha_frac"]) < 0.35:
        return False
    if "def " not in c:
        return False
    lines = c.splitlines()
    doc = c.count('"""') >= 2 or c.count("'''") >= 2
    com = sum(l.strip().startswith("#") for l in lines) >= 0.05 * max(1, len(lines))
    return doc or com


def chunks(it, n):
    buf = []
    for x in it:
        buf.append(x)
        if len(buf) == n:
            yield buf; buf = []
    if buf:
        yield buf


def build_py(a, pool):
    from datasets import load_dataset
    ds = load_dataset("codeparrot/codeparrot-clean", split="train", streaming=True)
    seen = kept = total = 0
    shard, buf, T0 = 0, [], time.time()

    def gen():
        nonlocal seen, kept
        for r in ds:
            seen += 1
            if keep(r):
                kept += 1
                yield r["content"]

    for arr in pool.imap(_enc, chunks(gen(), 200)):
        buf.append(arr); total += len(arr)
        if sum(map(len, buf)) >= 100_000_000 or total >= a.target:
            np.save(f"{OUT}/py_{shard:03d}.npy", np.concatenate(buf)); shard += 1; buf = []
            print(f"[{time.time()-T0:.0f}s] mảnh {shard} · {total/1e6:.0f}M token · giữ {kept}/{seen} file "
                  f"({100*kept/max(1,seen):.0f}%)", flush=True)
        if total >= a.target:
            break
    if buf:
        np.save(f"{OUT}/py_{shard:03d}.npy", np.concatenate(buf))
    return {"py_tokens": total, "py_files_kept": kept, "py_files_seen": seen}


def build_inst(pool):
    from datasets import load_dataset
    texts = []
    for r in load_dataset("ise-uiuc/Magicoder-OSS-Instruct-75K", split="train"):
        texts.append(f"Hỏi: {r['problem'].strip()}\nĐáp: {r['solution'].strip()}")
    for r in load_dataset("m-a-p/CodeFeedback-Filtered-Instruction", split="train"):
        texts.append(f"Hỏi: {r['query'].strip()}\nĐáp: {r['answer'].strip()}")
    for r in load_dataset("nickrosh/Evol-Instruct-Code-80k-v1", split="train"):
        texts.append(f"Hỏi: {r['instruction'].strip()}\nĐáp: {r['output'].strip()}")
    import random
    random.Random(104).shuffle(texts)
    arr = np.concatenate(list(pool.imap(_enc, chunks(texts, 200))))
    np.save(f"{OUT}/inst_000.npy", arr)
    print(f"bài tập có lời-giải: {len(texts)} mẫu · {len(arr)/1e6:.0f}M token", flush=True)
    return {"inst_docs": len(texts), "inst_tokens": int(len(arr))}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--target", type=int, default=900_000_000, help="số token Python cần gom")
    ap.add_argument("--workers", type=int, default=24)
    a = ap.parse_args()
    os.makedirs(OUT, exist_ok=True)
    with Pool(a.workers, initializer=_init) as pool:
        st = build_inst(pool)
        st.update(build_py(a, pool))
    json.dump(st, open(f"{OUT}/stats.json", "w"), indent=1)
    print("### xong", st, flush=True)


if __name__ == "__main__":
    main()
